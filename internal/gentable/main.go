// Command gentable writes secretscan/entropy_table.go: the 1st-percentile
// Shannon entropy, by nearest rank, of 20,000 uniformly random strings for
// each alphabet and each length from the alphabet's minimum to 64
// (docs/design.md §5). The seed is fixed, so the table is reproducible;
// the layer 4 test regenerates it and requires it byte-identical.
//
//	go run ./internal/gentable > secretscan/entropy_table.go
package main

import (
	"fmt"
	"math"
	"math/rand/v2"
	"os"
	"sort"
	"strings"
)

// Alphabets and minimum lengths, as docs/design.md §5 states them.
var alphabets = []struct {
	name, chars string
	min         int
}{
	{"decimal", "0123456789", 16},
	{"hex", "0123456789abcdef", 16},
	{"alnum", "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-", 12},
	{"base64", "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=_-", 16},
	{"printable", printable(), 12},
}

func printable() string {
	var b strings.Builder
	for c := 33; c <= 126; c++ {
		b.WriteByte(byte(c))
	}
	return b.String()
}

const (
	seed    = 289
	samples = 20000
	maxLen  = 64
)

func shannon(s []byte) float64 {
	var counts [256]int
	for _, c := range s {
		counts[c]++
	}
	n := float64(len(s))
	h := 0.0
	for _, c := range counts {
		if c > 0 {
			p := float64(c) / n
			h -= p * math.Log2(p)
		}
	}
	return h
}

func main() {
	rng := rand.New(rand.NewPCG(seed, seed))
	var b strings.Builder
	b.WriteString("// Code generated by go run ./internal/gentable; DO NOT EDIT.\n\npackage secretscan\n\n")
	b.WriteString("// entropyFloor[alphabet][length] is the 1st-percentile Shannon entropy,\n// in millibits per character, of uniformly random strings (docs/design.md §5).\nvar entropyFloor = map[string]map[int]int{\n")
	for _, a := range alphabets {
		fmt.Fprintf(&b, "\t%q: {", a.name)
		for l := a.min; l <= maxLen; l++ {
			hs := make([]float64, samples)
			buf := make([]byte, l)
			for i := range hs {
				for j := range buf {
					buf[j] = a.chars[rng.IntN(len(a.chars))]
				}
				hs[i] = shannon(buf)
			}
			sort.Float64s(hs)
			p1 := hs[int(math.Ceil(0.01*samples))-1]
			fmt.Fprintf(&b, "%d: %d, ", l, int(math.Floor(p1*1000)))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	os.Stdout.WriteString(b.String())
}
